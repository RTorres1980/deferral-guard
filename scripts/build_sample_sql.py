"""Generate db/06_sample_data.sql from data/sample/*.csv.

Keeps the Oracle sample load and the Python test fixtures in lockstep:
    python scripts/build_sample_sql.py
"""
from __future__ import annotations

import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SAMPLE = ROOT / "data" / "sample"
OUT = ROOT / "db" / "06_sample_data.sql"

# load order respects foreign keys
TABLES = [
    ("plans.csv", "dg_plans"),
    ("participants.csv", "dg_participants"),
    ("deferral_elections.csv", "dg_deferral_elections"),
    ("subsequent_elections.csv", "dg_subsequent_elections"),
    ("distribution_requests.csv", "dg_distribution_requests"),
]

DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
NUM_RE = re.compile(r"^-?\d+(\.\d+)?$")


def literal(value: str) -> str:
    if value == "":
        return "NULL"
    if DATE_RE.match(value):
        return f"DATE '{value}'"
    if NUM_RE.match(value):
        return value
    return "'" + value.replace("'", "''") + "'"


def main() -> None:
    lines = [
        "-- Generated by scripts/build_sample_sql.py from data/sample. Do not edit by hand.",
        "-- All names and sponsors are fictional.",
        "",
    ]
    for filename, table in TABLES:
        with (SAMPLE / filename).open(newline="", encoding="utf-8") as fh:
            reader = csv.DictReader(fh)
            cols = ", ".join(c.lower() for c in reader.fieldnames)
            for row in reader:
                vals = ", ".join(literal(row[c]) for c in reader.fieldnames)
                lines.append(f"INSERT INTO {table} ({cols}) VALUES ({vals});")
        lines.append("")
    lines += ["COMMIT;", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
